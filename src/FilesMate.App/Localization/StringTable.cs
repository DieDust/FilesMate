    public static string Get(string key)
    {
        var resolved = Resolver?.Invoke(key);
        if (!string.IsNullOrEmpty(resolved))
        {
            return resolved;
        }

        return GetForCulture(key, UseUiCulture ? CultureInfo.CurrentUICulture : CultureInfo.GetCultureInfo("en-US"));
    }

    public static string GetForCulture(string key, CultureInfo culture)
    {
        var translated = culture.TwoLetterISOLanguageName switch
        {
            "zh" => Chinese,
            "ja" => Japanese,
            _ => English,
        };
        if (translated.TryGetValue(key, out var value)) return value;
        if (Additional.TryGetValue(key, out var entry)) return culture.TwoLetterISOLanguageName switch
        {
            "zh" => entry.Chinese,
            "ja" => entry.Japanese,
            _ => entry.English,
        };
        return English.TryGetValue(key, out value) ? value : key;
    }

    public static string Format(string key, params object?[] arguments) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), arguments);

    public static string Html(string key) => System.Net.WebUtility.HtmlEncode(Get(key));
